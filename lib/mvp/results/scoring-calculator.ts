/**
 * Determine evidence status for a criterion.
 *
 * 1. Check AI-supplied quotes first.
 * 2. If no valid AI quote, search transcript using criterion-specific patterns.
 * 3. If patterns found → VERIFIED. If patterns NOT found:
 *    - System-level criteria → NOT_OBSERVED (event data wasn't available)
 *    - Conversation criteria → INVALIDATED (topic not in call)
 * 4. If AI said not_observed → NOT_OBSERVED (no search needed).
 */
function determineEvidenceStatus(
  criterionId: string,
  label: string,
  aiEvidence: string[],
  transcriptText: string,
  status: string,
): { status: 'verified' | 'invalidated' | 'not_observed'; quote: string } {
  const lowerTranscript = transcriptText.toLowerCase();

  // Step 1: If AI said not_observed, no evidence expected
  if (status === 'not_observed') {
    return { status: 'not_observed', quote: '' };
  }

  // Step 2: Check AI-supplied evidence quotes
  if (aiEvidence && aiEvidence.length > 0) {
    for (const e of aiEvidence) {
      if (isAutoGenerated(e)) continue;
      const trimmed = e.trim();
      if (trimmed.length >= 5 && transcriptText.includes(trimmed)) {
        return { status: 'verified', quote: trimmed };
      }
    }
  }

  // Step 3: Search transcript using criterion patterns
  const patterns = EVIDENCE_PATTERNS[criterionId];
  if (patterns) {
    for (const pattern of patterns) {
      const idx = lowerTranscript.indexOf(pattern);
      if (idx !== -1) {
        // Found — extract the full line as evidence
        const lineStart = transcriptText.lastIndexOf('\n', idx) + 1;
        const lineEnd = transcriptText.indexOf('\n', idx + pattern.length);
        const snippet = transcriptText.slice(
          lineStart,
          lineEnd !== -1 ? lineEnd : transcriptText.length
        ).trim();
        return { status: 'verified', quote: snippet };
      }
    }
    // Patterns exist but none found → the topic was actively searched for and not found.
    // If it's a fundamental criterion, don't invalidate — it's expected on every call.
    // Return not_observed (the candidate gets 0 for not doing it).
    if (FUNDAMENTAL_CRITERIA.has(criterionId)) {
      return { status: 'not_observed', quote: '' };
    }
    // Framework-specific criteria: topic not discussed → invalidated (not applicable to this scenario)
    return { status: 'invalidated', quote: '' };
  }

  // Step 4: No patterns for this criterion, no AI quote.
  // If status is 'fail' and it's NOT a fundamental criterion, it was consciously
  // checked and failed → invalidated (topic not discussed in this call).
  // Fundamental criteria should never be invalidated — score as 0 instead.
  if (status === 'fail') {
    if (!FUNDAMENTAL_CRITERIA.has(criterionId)) {
      return { status: 'invalidated', quote: '' };
    }
    return { status: 'not_observed', quote: '' };
  }

  // Fallback: extract key words from label, search transcript
  const labelWords = label.toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .split(/\s+/)
    .filter(w => w.length > 3 && !['ticket', 'candidate', 'about', 'issue', 'clear', 'asked', 'used', 'the', 'and', 'for', 'not'].includes(w));
  for (const word of labelWords) {
    const idx = lowerTranscript.indexOf(word);
    if (idx !== -1) {
      const lineStart = transcriptText.lastIndexOf('\n', idx) + 1;
      const lineEnd = transcriptText.indexOf('\n', idx + word.length);
      const snippet = transcriptText.slice(lineStart, lineEnd !== -1 ? lineEnd : transcriptText.length).trim();
      return { status: 'verified', quote: snippet };
    }
  }

  return { status: 'not_observed', quote: '' };
}

/* ── Main calculator ── */

export function computeScoredAssessment(criteria: CriterionResult[], transcriptText: string): ScoredAssessment {
  const findings: ValidationFinding[] = [];
  let rawEarned = 0, rawMax = 0;
  let validatedEarned = 0;
  let verifiedCount = 0, invalidatedCount = 0, applicableCount = 0;

  for (const c of criteria) {
    if (c.status === 'not_applicable') continue;
    applicableCount++;

    const multiplier = c.status === 'pass' ? 1 : c.status === 'partial' ? 0.5 : 0;
    const earned = c.weight * multiplier;

    rawEarned += earned;
    rawMax += c.weight;

    // Determine evidence status
    const ev = determineEvidenceStatus(c.id, c.label, c.evidence, transcriptText, c.status);
    c.evidenceStatus = ev.status;
    c.evidenceQuote = ev.quote;

    if (ev.status === 'verified') {
      validatedEarned += earned;
      verifiedCount++;
    } else if (ev.status === 'invalidated') {
      // Invalidated: topic not in transcript. Exclude from validated score entirely.
      // This criterion is not relevant to this call.
      invalidatedCount++;
      // Subtract from raw since it's not applicable
      rawEarned -= earned;
      rawMax -= c.weight;
    }
    // not_observed: counts in raw (as 0), doesn't affect validated
  }

  const rawScore = rawMax > 0 ? Math.round((rawEarned / rawMax) * 100) : 0;
  const validatedScore = rawMax > 0 ? Math.round((validatedEarned / rawMax) * 100) : 0;
  const evidenceQuality = rawScore > 0 ? Math.round((validatedScore / rawScore) * 100) : 0;

  const verdict = validatedScore >= 60 ? 'PASS' : 'FAIL';

  return {
    rawScore,
    validatedScore,
    evidenceQuality,
    totalCriteria: criteria.length,
    applicableCriteria: applicableCount,
    verifiedCount,
    invalidatedCount,
    findings,
    verdict,
  };
}

/* ── Builder ── */

export function buildCriteriaFromFrameworks(
  frameworkResults: Array<{ frameworkId: string; frameworkName: string; criteriaResults: Array<{ criterionId: string; label: string; status: string; evidence: string; pointsEarned: number; pointsMax: number }> }>,
): CriterionResult[] {
  const results: CriterionResult[] = [];
  for (const fw of frameworkResults) {
    for (const c of (fw.criteriaResults || [])) {
      results.push({
        id: c.criterionId,
        label: c.label,
        description: CRITERION_DESCRIPTIONS[c.criterionId] || c.label,
        status: c.status as any,
        weight: c.pointsMax || 1,
        evidence: c.evidence ? [c.evidence] : [],
        frameworkId: fw.frameworkId,
        frameworkName: fw.frameworkName,
        evidenceStatus: 'not_observed',
        evidenceQuote: '',
      });
    }
  }
  return results;
}
