/**
 * Evidence-Validated Scoring Calculator
 *
 * Three evidence states:
 *  - verified:     transcript quote found → criterion counts normally
 *  - invalidated:  topic searched for but NOT in transcript → excluded (not applicable to this call)
 *  - not_observed: AI couldn't determine → counts as 0 (no penalty, no flag)
 *
 * Validated score uses same denominator as raw (all applicable criteria).
 * Only verified criteria contribute to numerator. This guarantees validated ≤ raw.
 */

export interface CriterionResult {
  id: string;
  label: string;
  description: string;       // what this criterion actually checks, with examples
  status: 'pass' | 'partial' | 'fail' | 'not_observed' | 'not_applicable';
  weight: number;
  evidence: string[];
  frameworkId: string;
  frameworkName: string;
  evidenceStatus: 'verified' | 'invalidated' | 'not_observed';
  evidenceQuote: string;
}

export interface ValidationFinding {
  criterionId: string;
  label: string;
  frameworkName: string;
  message: string;
}

export interface ScoredAssessment {
  rawScore: number;
  validatedScore: number;
  evidenceQuality: number;    // validatedScore / rawScore — how much of the score is on verified evidence
  totalCriteria: number;
  applicableCriteria: number;
  verifiedCount: number;
  invalidatedCount: number;
  findings: ValidationFinding[];
  verdict: 'PASS' | 'FAIL';
}

