/**
 * Evidence-Validated Scoring Calculator
 *
 * Every criterion requires a transcript quote as evidence.
 * The validator checks each quote exists verbatim in the transcript.
 * Only evidence-validated criteria count toward the validated score.
 *
 * This is fully deterministic — no AI involved in validation.
 */

export interface CriterionResult {
  id: string;
  label: string;
  status: 'pass' | 'partial' | 'fail' | 'not_observed' | 'not_applicable';
  weight: number;
  evidence: string[];
  frameworkId: string;
  frameworkName: string;
  evidenceStatus: EvidenceStatus;
  evidenceQuote: string;
}

export interface ValidationFinding {
  type: 'no_evidence' | 'ai_quote_not_found';
  criterionId: string;
  label: string;
  frameworkName: string;
  reason: string;
  pointsAtRisk: number;
}

export interface ScoredAssessment {
  rawScore: number;
  validatedScore: number;   // only criteria with verified evidence
  totalCriteria: number;
  applicableCriteria: number;
  findings: ValidationFinding[];
  warnings: string[];
  verdict: 'PASS' | 'FAIL';
}

export type EvidenceStatus = 'verified_ai' | 'verified_deterministic' | 'ai_quote_not_found' | 'no_evidence';

const AUTO_PREFIXES = [
  'Event "', 'Content found', 'Not found', 'Keyword found', 'Keyword not',
  'Action "', 'PROHIBITED action', 'Action correctly', 'Found in triage',
  'Not applicable', '[fixture', 'Unknown check',
];

function isAutoGenerated(e: string): boolean {
  if (!e || e.length < 5) return true;
  if (AUTO_PREFIXES.some(pref => e.startsWith(pref))) return true;
  if (e === 'not_observed' || e === 'pass' || e === 'fail' || e === 'partial') return true;
  return false;
}

function validateEvidence(evidence: string[], transcriptText: string): { status: EvidenceStatus; quote: string } {
  if (!evidence || evidence.length === 0) return { status: 'no_evidence', quote: '' };

  let allAuto = true;

  for (const e of evidence) {
    if (isAutoGenerated(e)) continue;
    allAuto = false;

    const trimmed = e.trim();
    if (trimmed.length < 5) continue;

    if (transcriptText.includes(trimmed)) {
      return { status: 'verified_ai', quote: trimmed };
    }
  }

  if (allAuto) {
    return { status: 'verified_deterministic', quote: '' };
  }

  const firstReal = evidence.find(e => !isAutoGenerated(e));
  return { status: 'ai_quote_not_found', quote: firstReal?.trim() || '' };
}

export function computeScoredAssessment(
  criteria: CriterionResult[],
  transcriptText: string,
): ScoredAssessment {
  const findings: ValidationFinding[] = [];
  const warnings: string[] = [];

  let rawEarned = 0;
  let rawMax = 0;
  let validatedEarned = 0;
  let validatedMax = 0;
  let applicableCount = 0;

  for (const c of criteria) {
    if (c.status === 'not_applicable') continue;
    applicableCount++;

    const multiplier = c.status === 'pass' ? 1 : c.status === 'partial' ? 0.5 : 0;
    const earned = c.weight * multiplier;

    // Always count toward raw
    rawEarned += earned;
    rawMax += c.weight;

    // ── Evidence validation ──
    const ev = validateEvidence(c.evidence, transcriptText);
    c.evidenceStatus = ev.status;
    c.evidenceQuote = ev.quote;

    const countsTowardValidated = ev.status === 'verified_ai' || ev.status === 'verified_deterministic';

    if (!countsTowardValidated) {
      let reason: string;
      let type: 'no_evidence' | 'ai_quote_not_found';

      if (ev.status === 'no_evidence') {
        reason = `No evidence provided.`;
        type = 'no_evidence';
      } else {
        reason = `Quote "${ev.quote.substring(0, 60)}..." not found verbatim in transcript.`;
        type = 'ai_quote_not_found';
      }

      findings.push({
        type,
        criterionId: c.id,
        label: c.label,
        frameworkName: c.frameworkName,
        reason,
        pointsAtRisk: earned,
      });
    }

    if (countsTowardValidated) {
      validatedEarned += earned;
      validatedMax += c.weight;
    }
  }

  const rawScore = rawMax > 0 ? Math.round((rawEarned / rawMax) * 100) : 0;
  const validatedScore = validatedMax > 0 ? Math.round((validatedEarned / validatedMax) * 100) : 0;

  if (findings.length > 0) {
    const noQuote = findings.filter(f => f.type === 'no_evidence').length;
    const notFound = findings.filter(f => f.type === 'ai_quote_not_found').length;
    const parts: string[] = [];
    if (noQuote > 0) parts.push(`${noQuote} missing evidence quotes`);
    if (notFound > 0) parts.push(`${notFound} quotes not found in transcript`);
    warnings.push(`${findings.length} criteria flagged (${parts.join(', ')}). Validated score excludes them.`);
  }

  const verdict = validatedScore >= 60 ? 'PASS' : 'FAIL';

  return {
    rawScore,
    validatedScore: Math.max(0, validatedScore),
    totalCriteria: criteria.length,
    applicableCriteria: applicableCount,
    findings,
    warnings,
    verdict,
  };
}

const AUTO_EVIDENCE_PREFIXES = [
  'Event "', 'Content found', 'Not found', 'Keyword found', 'Keyword not',
  'Action "', 'PROHIBITED action', 'Action correctly', 'Found in triage',
  'Not applicable', '[fixture', 'Unknown check',
];

export function hasRealEvidence(evidence: string[]): boolean {
  if (!evidence || evidence.length === 0) return false;
  return evidence.some(e => {
    if (!e || e.length < 5) return false;
    if (AUTO_EVIDENCE_PREFIXES.some(pref => e.startsWith(pref))) return false;
    if (e === 'not_observed' || e === 'pass' || e === 'fail' || e === 'partial') return false;
    return true;
  });
}

export function buildCriteriaFromFrameworks(
  frameworkResults: Array<{ frameworkId: string; frameworkName: string; criteriaResults: Array<{ criterionId: string; label: string; status: string; evidence: string; pointsEarned: number; pointsMax: number }> }>,
): CriterionResult[] {
  const results: CriterionResult[] = [];
  for (const fw of frameworkResults) {
    for (const c of (fw.criteriaResults || [])) {
      results.push({
        id: c.criterionId,
        label: c.label,
        status: c.status as any,
        weight: c.pointsMax || 1,
        evidence: c.evidence ? [c.evidence] : [],
        frameworkId: fw.frameworkId,
        frameworkName: fw.frameworkName,
        evidenceStatus: 'no_evidence',
        evidenceQuote: '',
      });
    }
  }
  return results;
}
