/**
 * Try to find evidence in the transcript for a given criterion.
 * First checks AI-supplied quotes, then falls back to smart matching.
 */
function findEvidence(
  criterionId: string,
  label: string,
  aiEvidence: string[],
  transcriptText: string,
  status: string,
): { status: EvidenceStatus; quote: string; foundBy: 'ai' | 'validator' } {
  const lowerTranscript = transcriptText.toLowerCase();

  /* Step 1: Check AI-supplied evidence */
  if (aiEvidence && aiEvidence.length > 0) {
    for (const e of aiEvidence) {
      if (isAutoGenerated(e)) continue;
      const trimmed = e.trim();
      if (trimmed.length >= 5 && transcriptText.includes(trimmed)) {
        return { status: 'verified', quote: trimmed, foundBy: 'ai' };
      }
    }
  }

  /* Step 2: If not_observed or not_applicable, no evidence expected */
  if (status === 'not_observed' || status === 'not_applicable') {
    return { status: 'verified', quote: '', foundBy: 'validator' };
  }

    /* Step 3: Validator searches transcript using criterion's expected patterns */
  const patterns = EVIDENCE_PATTERNS[criterionId];
  if (patterns) {
    for (const pattern of patterns) {
      const idx = lowerTranscript.indexOf(pattern);
      if (idx !== -1) {
        // Snap to line start, extract a complete utterance
        const lineStart = transcriptText.lastIndexOf('\n', idx) + 1;
        const lineEnd = transcriptText.indexOf('\n', idx + pattern.length);
        const snippet = transcriptText.slice(
          lineStart,
          lineEnd !== -1 ? lineEnd : transcriptText.length
        ).trim();
        // Store the FULL line — only truncate for display
        return { status: 'verified', quote: snippet, foundBy: 'validator' };
      }
    }
  }

  /* Step 4: Fallback — search by extracting key terms from the label */
  const labelLower = label.toLowerCase();
  const words = labelLower
    .replace(/[^a-z0-9\s]/g, '')
    .split(/\s+/)
    .filter(w => w.length > 4 && !['ticket', 'candidate', 'about', 'issue', 'clear', 'asked', 'used'].includes(w));

  for (const word of words) {
    const idx = lowerTranscript.indexOf(word);
    if (idx !== -1) {
      const lineStart = transcriptText.lastIndexOf('\n', idx) + 1;
      const lineEnd = transcriptText.indexOf('\n', idx + word.length);
      const snippet = transcriptText.slice(
        lineStart,
        lineEnd !== -1 ? lineEnd : transcriptText.length
      ).trim();
      return { status: 'verified', quote: snippet, foundBy: 'validator' };
    }
  }

  return { status: 'no_evidence', quote: '', foundBy: 'validator' };
}

/* ── Main calculator ── */

export function computeScoredAssessment(criteria: CriterionResult[], transcriptText: string): ScoredAssessment {
  const findings: ValidationFinding[] = [];
  const warnings: string[] = [];

  let rawEarned = 0;
  let rawMax = 0;
  let validatedEarned = 0;
  let validatedMax = 0;
  let applicableCount = 0;

  for (const c of criteria) {
    if (c.status === 'not_applicable') continue;
    applicableCount++;

    const multiplier = c.status === 'pass' ? 1 : c.status === 'partial' ? 0.5 : 0;
    const earned = c.weight * multiplier;

    rawEarned += earned;
    rawMax += c.weight;

    // Find evidence (AI-supplied or validator-found)
    const ev = findEvidence(c.id, c.label, c.evidence, transcriptText, c.status);
    c.evidenceStatus = ev.status;
    c.evidenceQuote = ev.quote;

    if (ev.status === 'verified') {
      validatedEarned += earned;
      validatedMax += c.weight;
    } else if (earned > 0) {
      // Only flag criteria that actually contributed points but have no evidence
      findings.push({
        type: 'no_evidence',
        criterionId: c.id,
        label: c.label,
        frameworkName: c.frameworkName,
        reason: `No matching evidence found in transcript for this criterion.`,
        pointsAtRisk: earned,
      });
    }
    // If earned is 0 (failed or not_observed mapped to pass), no need to flag —
    // the criterion didn't contribute points anyway.
  }

  const rawScore = rawMax > 0 ? Math.round((rawEarned / rawMax) * 100) : 0;

  // FIX: validated score uses SAME denominator as raw (rawMax), not validatedMax.
  // Only the numerator changes — we only count verified criteria's earned points.
  // This guarantees validated <= raw always.
  const validatedScore = rawMax > 0 ? Math.round((validatedEarned / rawMax) * 100) : 0;

  if (findings.length > 0) {
    warnings.push(`${findings.length} criteria flagged — no matching evidence found in transcript. ${validatedScore}/${rawScore}`);
  }

  const verdict = validatedScore >= 60 ? 'PASS' : 'FAIL';

  return {
    rawScore,
    validatedScore: Math.max(0, validatedScore),
    totalCriteria: criteria.length,
    applicableCriteria: applicableCount,
    findings,
    warnings,
    verdict,
  };
}

/* ── Builder ── */

export function buildCriteriaFromFrameworks(
  frameworkResults: Array<{ frameworkId: string; frameworkName: string; criteriaResults: Array<{ criterionId: string; label: string; status: string; evidence: string; pointsEarned: number; pointsMax: number }> }>,
): CriterionResult[] {
  const results: CriterionResult[] = [];
  for (const fw of frameworkResults) {
    for (const c of (fw.criteriaResults || [])) {
      results.push({
        id: c.criterionId,
        label: c.label,
        status: c.status as any,
        weight: c.pointsMax || 1,
        evidence: c.evidence ? [c.evidence] : [],
        frameworkId: fw.frameworkId,
        frameworkName: fw.frameworkName,
        evidenceStatus: 'no_evidence',
        evidenceQuote: '',
      });
    }
  }
  return results;
}
